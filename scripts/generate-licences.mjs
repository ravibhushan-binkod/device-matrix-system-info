/**
 * Generates `src/features/legal/licences.ts` — the open-source licence list the
 * About screen shows.
 *
 * The list is built from the runtime `dependencies` in package.json: each
 * package's own `package.json` supplies the name, installed version, licence
 * and home page. Nothing is fetched from the network and no dependency is
 * installed. Transitive libraries ship under their own licences inside the
 * packages that use them; the generated header says so.
 *
 * Run with: npm run licences
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const require = createRequire(import.meta.url);

function licenceText(value) {
  if (typeof value === 'string') return value;
  if (Array.isArray(value)) {
    const parts = value.map(licenceText).filter(Boolean);
    return parts.length > 0 ? parts.join(' OR ') : null;
  }
  if (value != null && typeof value === 'object' && typeof value.type === 'string') {
    return value.type;
  }
  return null;
}

function homePage(info) {
  if (typeof info.homepage === 'string' && info.homepage.length > 0) return info.homepage;
  const url = info.repository && (info.repository.url ?? info.repository);
  if (typeof url !== 'string' || url.length === 0) return null;
  return url
    .replace(/^git\+/, '')
    .replace(/\.git$/, '')
    .replace(/^git:\/\//, 'https://');
}

const project = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const names = Object.keys(project.dependencies ?? {}).sort((a, b) => a.localeCompare(b));

const entries = [];
for (const name of names) {
  let info;
  try {
    info = JSON.parse(readFileSync(require.resolve(`${name}/package.json`), 'utf8'));
  } catch {
    // Some packages do not export ./package.json — read the installed folder.
    try {
      info = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
    } catch {
      info = { name, version: 'installed version unknown', license: null };
    }
  }
  entries.push({
    name: info.name ?? name,
    version: typeof info.version === 'string' ? info.version : 'unknown',
    licence: licenceText(info.license) ?? 'see package',
    homepage: homePage(info),
  });
}

// Assets that ship in the bundle but are not npm dependencies.
entries.push({
  name: 'Simple Icons (brand logos)',
  version: 'checked 2026-10-21',
  licence: 'CC0 1.0',
  homepage: 'https://simpleicons.org',
});

const today = new Date().toISOString().slice(0, 10);
const lines = [];
lines.push('/**');
lines.push(' * Open-source licence list for the direct runtime dependencies.');
lines.push(' *');
lines.push(' * Generated by scripts/generate-licences.mjs — do not edit by hand.');
lines.push(` * Generated on ${today} from the installed packages in node_modules.`);
lines.push(' *');
lines.push(' * Transitive libraries ship inside these packages under their own');
lines.push(' * licences; the About screen links to each project so the full text can');
lines.push(' * be read there.');
lines.push(' */');
lines.push('');
lines.push('export type LicenceEntry = {');
lines.push('  name: string;');
lines.push('  version: string;');
lines.push('  licence: string;');
lines.push('  homepage: string | null;');
lines.push('};');
lines.push('');
lines.push('export const LICENCES: LicenceEntry[] = [');
for (const entry of entries) {
  lines.push('  {');
  lines.push(`    name: ${JSON.stringify(entry.name)},`);
  lines.push(`    version: ${JSON.stringify(entry.version)},`);
  lines.push(`    licence: ${JSON.stringify(entry.licence)},`);
  lines.push(`    homepage: ${entry.homepage == null ? 'null' : JSON.stringify(entry.homepage)},`);
  lines.push('  },');
}
lines.push('];');
lines.push('');

const target = join(root, 'src', 'features', 'legal', 'licences.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, lines.join('\n'), 'utf8');
console.log(`Wrote ${target} (${entries.length} entries)`);
